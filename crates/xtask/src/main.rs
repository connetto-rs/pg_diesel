//! Repository automation for `pg_diesel`, run as `cargo xtask <command>`.
//!
//! `generate` writes every `crates/pg_diesel_pgN` package from the templates
//! in `versioned/`, each with its `postgres-N` gates resolved for N, and
//! `generate --check` fails when the committed packages differ from a fresh
//! run.

mod gates;

use std::{
    collections::BTreeMap,
    fs, io,
    io::Write as _,
    path::{Path, PathBuf},
    process::{Command, ExitCode, Stdio},
};

/// The `PostgreSQL` major versions a package is generated for.
const MAJORS: [u32; 5] = [14, 15, 16, 17, 18];

/// Why generating the version packages failed.
#[derive(Debug, thiserror::Error)]
enum GenerateError {
    /// A file could not be read, written or listed.
    #[error("{path}: {source}")]
    Io {
        /// The file or directory involved.
        path: PathBuf,
        /// The underlying error.
        source: io::Error,
    },
    /// A template could not be resolved for a version.
    #[error("{path} for PostgreSQL {major}: {source}")]
    Gate {
        /// The template.
        path: PathBuf,
        /// The version it was resolved for.
        major: u32,
        /// What went wrong.
        source: gates::GateError,
    },
    /// `rustfmt` could not format a generated file.
    #[error("rustfmt failed on the output for {path}: {message}")]
    Format {
        /// The template the output came from.
        path: PathBuf,
        /// What `rustfmt` reported.
        message: String,
    },
    /// The committed packages differ from a fresh run.
    #[error("these generated files are stale, run `cargo xtask generate`:\n{0}")]
    Stale(String),
}

fn main() -> ExitCode {
    let arguments: Vec<String> = std::env::args().skip(1).collect();
    let check = match arguments.iter().map(String::as_str).collect::<Vec<_>>()[..] {
        ["generate"] => false,
        ["generate", "--check"] => true,
        _ => {
            eprintln!("usage: cargo xtask generate [--check]");
            return ExitCode::FAILURE;
        }
    };
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    match generate(&root, check) {
        Ok(()) => ExitCode::SUCCESS,
        Err(error) => {
            eprintln!("{error}");
            ExitCode::FAILURE
        }
    }
}

/// Writes, or with `check` compares, every version package under `root`.
fn generate(root: &Path, check: bool) -> Result<(), GenerateError> {
    let templates = rust_files(&root.join("versioned"))?;
    let mut stale = Vec::new();
    for major in MAJORS {
        let package = root.join(format!("crates/pg_diesel_pg{major}"));
        let mut wanted = BTreeMap::new();
        wanted.insert(package.join("Cargo.toml"), manifest(major));
        wanted.insert(package.join("README.md"), readme(major));
        for relative in &templates {
            let template = root.join("versioned").join(relative);
            let source = read(&template)?;
            let resolved =
                gates::resolve(&source, major).map_err(|source| GenerateError::Gate {
                    path: template.clone(),
                    major,
                    source,
                })?;
            if let Some(resolved) = resolved {
                let header = format!(
                    "// @generated by `cargo xtask generate` from `versioned/{}`, edit that file instead.\n",
                    relative.display()
                );
                let formatted = rustfmt(&format!("{header}{resolved}"), &template)?;
                wanted.insert(package.join("src").join(relative), formatted);
            }
        }
        let source_directory = package.join("src");
        let present = if source_directory.exists() {
            rust_files(&source_directory)?
        } else {
            Vec::new()
        };
        for relative in present {
            let path = package.join("src").join(&relative);
            if !wanted.contains_key(&path) {
                if check {
                    stale.push(path.display().to_string());
                } else {
                    fs::remove_file(&path).map_err(|source| GenerateError::Io {
                        path: path.clone(),
                        source,
                    })?;
                }
            }
        }
        for (path, content) in wanted {
            let current = fs::read_to_string(&path).ok();
            if current.as_deref() == Some(content.as_str()) {
                continue;
            }
            if check {
                stale.push(path.display().to_string());
                continue;
            }
            if let Some(parent) = path.parent() {
                fs::create_dir_all(parent).map_err(|source| GenerateError::Io {
                    path: parent.to_path_buf(),
                    source,
                })?;
            }
            fs::write(&path, content).map_err(|source| GenerateError::Io {
                path: path.clone(),
                source,
            })?;
        }
    }
    if stale.is_empty() {
        Ok(())
    } else {
        Err(GenerateError::Stale(stale.join("\n")))
    }
}

/// Returns the `.rs` files under `directory`, relative to it and sorted.
fn rust_files(directory: &Path) -> Result<Vec<PathBuf>, GenerateError> {
    let mut found = Vec::new();
    let mut pending = vec![directory.to_path_buf()];
    while let Some(current) = pending.pop() {
        let entries = fs::read_dir(&current).map_err(|source| GenerateError::Io {
            path: current.clone(),
            source,
        })?;
        for entry in entries {
            let path = entry
                .map_err(|source| GenerateError::Io {
                    path: current.clone(),
                    source,
                })?
                .path();
            if path.is_dir() {
                pending.push(path);
            } else if path.extension().is_some_and(|extension| extension == "rs") {
                found.push(
                    path.strip_prefix(directory)
                        .expect("a listed file lies under its directory")
                        .to_path_buf(),
                );
            }
        }
    }
    found.sort();
    Ok(found)
}

/// Returns the content of `path`.
fn read(path: &Path) -> Result<String, GenerateError> {
    fs::read_to_string(path).map_err(|source| GenerateError::Io {
        path: path.to_path_buf(),
        source,
    })
}

/// Returns `source` as `rustfmt` lays it out.
fn rustfmt(source: &str, template: &Path) -> Result<String, GenerateError> {
    let format_error = |message: String| GenerateError::Format {
        path: template.to_path_buf(),
        message,
    };
    let mut child = Command::new("rustfmt")
        .args(["--edition", "2024", "--emit", "stdout"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .map_err(|error| format_error(error.to_string()))?;
    child
        .stdin
        .take()
        .expect("the child's stdin is piped")
        .write_all(source.as_bytes())
        .map_err(|error| format_error(error.to_string()))?;
    let output = child
        .wait_with_output()
        .map_err(|error| format_error(error.to_string()))?;
    if !output.status.success() {
        return Err(format_error(
            String::from_utf8_lossy(&output.stderr).into_owned(),
        ));
    }
    String::from_utf8(output.stdout).map_err(|error| format_error(error.to_string()))
}

/// The `Cargo.toml` of the `PostgreSQL` `major` package.
fn manifest(major: u32) -> String {
    format!(
        r#"# @generated by `cargo xtask generate`, edit `crates/xtask/src/main.rs` instead.
[package]
name = "pg_diesel_pg{major}"
version = "0.1.0"
edition = "2024"
description = "The PostgreSQL {major} catalog of pg_diesel"
license = "MIT"
readme = "README.md"

[dependencies]
pg_diesel_core = {{ path = "../pg_diesel_core", version = "0.1.0" }}
diesel = {{ workspace = true }}
serde = {{ workspace = true, optional = true }}
bigdecimal = {{ workspace = true }}

[features]
serde = ["dep:serde", "pg_diesel_core/serde"]

[lints]
workspace = true
"#
    )
}

/// The `README.md` of the `PostgreSQL` `major` package.
fn readme(major: u32) -> String {
    format!(
        "# `pg_diesel_pg{major}`\n\nThe tables and models of [`pg_diesel`](https://github.com/connetto-rs/pg_diesel) whose columns differ between server versions, as `PostgreSQL` {major} has them, beside the version-independent ones `pg_diesel_core` holds. `cargo xtask generate` writes this package from `versioned/`, so edit the files there. Depend on `pg_diesel`, which picks the catalog of the server it connects to.\n"
    )
}
