//! Shared-column definitions of the catalog relations whose columns differ
//! between `PostgreSQL` versions. Each holds only the columns every supported
//! version has, so a loader reading only those columns runs on any server.

/// Shared-column `information_schema` relations.
pub(crate) mod information_schema {
    diesel::table! {
        /// `information_schema.table_constraints` — view containing one row per table constraint.
        /// Includes primary keys, foreign keys, unique constraints, and check constraints.
        /// Provides metadata such as type, deferrability, enforcement, and null handling.
        information_schema.table_constraints (table_catalog, table_schema, table_name, constraint_name) {
            /// Catalog (database) containing the constraint.
            constraint_catalog -> Text,
            /// Schema containing the constraint.
            constraint_schema -> Text,
            /// Name of the constraint.
            constraint_name -> Text,
            /// Catalog (database) containing the table with the constraint.
            table_catalog -> Text,
            /// Schema containing the table with the constraint.
            table_schema -> Text,
            /// Name of the table containing the constraint.
            table_name -> Text,
            /// Type of the constraint: "PRIMARY KEY", "FOREIGN KEY", "UNIQUE", "CHECK".
            constraint_type -> Text,
            /// "YES" if the constraint is deferrable; "NO" otherwise.
            is_deferrable -> Text,
            /// "YES" if the constraint is initially deferred; "NO" otherwise.
            initially_deferred -> Text,
            /// "YES" if the constraint is enforced, "NO" if it is not.
            enforced -> Text,
        }
    }

    use crate::schema::information_schema::{columns::columns, key_column_usage::key_column_usage};
    diesel::allow_tables_to_appear_in_same_query!(table_constraints, columns);
    diesel::allow_tables_to_appear_in_same_query!(table_constraints, key_column_usage);
}

/// Shared-column `pg_catalog` relations.
pub(crate) mod pg_catalog {
    diesel::table! {
        /// `pg_attribute` — system catalog containing one row for each column (attribute) in a table,
        /// index, view, composite type, or foreign table.
        /// Stores metadata about column names, types, storage, nullability, defaults, identity, and inheritance.
        pg_catalog.pg_attribute (attrelid, attname, atttypid) {
            /// OID of the relation containing this column (references `pg_class.oid`).
            attrelid -> Oid,
            /// Name of the column.
            attname -> Text,
            /// OID of the column's data type (references `pg_type.oid`).
            atttypid -> Oid,
            /// Internal storage length of the column type.
            /// -1 = variable-length, -2 = C-string.
            attlen -> SmallInt,
            /// Column number:
            /// Positive = user-defined columns,
            /// 0 = table OID column,
            /// Negative = system columns.
            attnum -> SmallInt,
            /// Type-specific modifier (atttypmod), often indicating precision/scale for numeric types.
            /// -1 if not applicable.
            atttypmod -> Integer,
            /// `true` if the column's type is passed by value.
            attbyval -> Bool,
            /// Alignment requirement of the column type:
            /// 'c' = char, 's' = short, 'i' = int, 'd' = double.
            attalign -> Char,
            /// Storage strategy:
            /// 'p' = plain,
            /// 'e' = external,
            /// 'm' = main,
            /// 'x' = extended.
            attstorage -> Char,
            /// `true` if the column is marked NOT NULL.
            attnotnull -> Bool,
            /// `true` if the column has a default value.
            atthasdef -> Bool,
            /// `true` if the column has a missing value defined (for dropped/added columns).
            atthasmissing -> Bool,
            /// Identity column property:
            /// '' = not an identity column,
            /// 'a' = generated always,
            /// 'd' = generated by default.
            attidentity -> Char,
            /// Generated column property:
            /// '' = not generated,
            /// 's' = stored (generated always stored).
            attgenerated -> Char,
            /// `true` if the column has been dropped (still present for compatibility).
            attisdropped -> Bool,
            /// `true` if the column is locally defined (not inherited).
            attislocal -> Bool,
            /// OID of the collation of the column, or 0 if not collatable.
            attcollation -> Oid,
            /// Column-level options (e.g., for storage parameters); `NULL` if none.
            attoptions -> Nullable<Array<Text>>,
            /// Options for foreign data wrapper columns; `NULL` if none.
            attfdwoptions -> Nullable<Array<Text>>,
            /// Compression method for the column: 'p' = pglz, 'l' = lz4, or '' if no compression.
            attcompression -> Text,
            /// Missing value for added columns.
            attmissingval -> Nullable<Array<Text>>,
        }
    }

    diesel::table! {
        /// `pg_class` — system catalog containing one row for each table, index, sequence, view,
        /// materialized view, composite type, and TOAST table.
        /// Stores metadata such as storage, persistence, row count estimates, and relation type.
        pg_catalog.pg_class (oid, relname, relnamespace) {
            /// OID of the relation.
            oid -> Oid,
            /// Name of the relation (table, index, etc.).
            relname -> Text,
            /// OID of the namespace (schema) containing this relation.
            relnamespace -> Oid,
            /// OID of the composite type that represents the row type for this relation,
            /// or 0 if none.
            reltype -> Oid,
            /// OID of the underlying type if this is a typed table, else 0.
            reloftype -> Oid,
            /// OID of the role that owns the relation.
            relowner -> Oid,
            /// OID of the access method used (e.g., heap, B-tree, hash).
            relam -> Oid,
            /// Identifier of the relation's physical storage file (or 0 if none, such as for views).
            relfilenode -> Oid,
            /// OID of the tablespace containing the relation, or 0 for the database's default tablespace.
            reltablespace -> Oid,
            /// Number of disk pages the relation uses (as of last `ANALYZE`).
            relpages -> Integer,
            /// Estimated number of live rows in the relation (as of last `ANALYZE`).
            reltuples -> Float,
            /// Number of all-visible pages (from visibility map).
            relallvisible -> Integer,
            /// OID of the TOAST table associated with this relation, or 0 if none.
            reltoastrelid -> Oid,
            /// `true` if the relation has (or once had) an index.
            relhasindex -> Bool,
            /// `true` if the relation is shared across all databases (e.g., `pg_database`).
            relisshared -> Bool,
            /// Relation persistence:
            /// 'p' = permanent,
            /// 'u' = unlogged,
            /// 't' = temporary.
            relpersistence -> Char,
            /// Relation kind:
            /// 'r' = ordinary table,
            /// 'i' = index,
            /// 'S' = sequence,
            /// 't' = TOAST table,
            /// 'v' = view,
            /// 'm' = materialized view,
            /// 'c' = composite type,
            /// 'f' = foreign table,
            /// 'p' = partitioned table,
            /// 'I' = partitioned index.
            relkind -> Char,
            /// Number of user columns (attributes) in the relation.
            relnatts -> SmallInt,
            /// Number of check constraints on the relation.
            relchecks -> SmallInt,
            /// `true` if the relation has rules.
            relhasrules -> Bool,
            /// `true` if the relation has triggers.
            relhastriggers -> Bool,
            /// `true` if the relation has child tables (is a parent in inheritance).
            relhassubclass -> Bool,
            /// `true` if row-level security (RLS) is enabled.
            relrowsecurity -> Bool,
            /// `true` if row-level security (RLS) is forced for all users.
            relforcerowsecurity -> Bool,
            /// `true` if the table is currently populated (for materialized views).
            relispopulated -> Bool,
            /// Replica identity setting:
            /// 'd' = default (primary key),
            /// 'n' = nothing,
            /// 'f' = all columns,
            /// 'i' = index.
            relreplident -> Char,
            /// `true` if this relation is a partition of another table.
            relispartition -> Bool,
            /// OID of the relation this one is being rewritten into (during operations like `ALTER TABLE`), or 0.
            relrewrite -> Oid,
            /// Minimum frozen transaction ID for the relation (used by VACUUM).
            relfrozenxid -> Oid,
            /// Minimum frozen multixact ID for the relation (used by VACUUM).
            relminmxid -> Oid,
            /// Relation-level options for the relation.
            reloptions -> Nullable<Array<Text>>,
            /// Partition bound for partitioned tables.
            relpartbound -> Nullable<Text>,
        }
    }

    diesel::table! {
        /// `pg_catalog.pg_collation` — catalog of collations.
        /// Contains information about collations (sorting and character classification rules).
        pg_catalog.pg_collation (oid) {
            /// OID of the collation (primary key).
            oid -> diesel::sql_types::Oid,
            /// Name of the collation.
            collname -> Text,
            /// OID of the namespace containing this collation.
            collnamespace -> diesel::sql_types::Oid,
            /// OID of the owner of this collation.
            collowner -> diesel::sql_types::Oid,
            /// Provider of the collation (c=libc, i=icu, d=database default).
            collprovider -> Text,
            /// Whether the collation is deterministic.
            collisdeterministic -> Bool,
            /// Encoding for which this collation is applicable (-1 for any).
            collencoding -> Integer,
            /// `LC_COLLATE` setting for this collation.
            collcollate -> Nullable<Text>,
            /// `LC_CTYPE` setting for this collation.
            collctype -> Nullable<Text>,
            /// Provider-specific version string.
            collversion -> Nullable<Text>,
        }
    }

    diesel::table! {
        /// `pg_constraint` — system catalog containing one row for each table, domain, or index constraint.
        /// Stores metadata about primary keys, foreign keys, unique constraints, check constraints,
        /// exclusion constraints, and domain constraints.
        pg_catalog.pg_constraint (oid, conname, connamespace) {
            /// OID of the constraint.
            oid -> Oid,
            /// Name of the constraint (unique within the schema).
            conname -> Text,
            /// OID of the namespace (schema) containing the constraint.
            connamespace -> Oid,
            /// Constraint type:
            /// 'c' = check constraint,
            /// 'f' = foreign key,
            /// 'p' = primary key,
            /// 'u' = unique constraint,
            /// 't' = constraint trigger,
            /// 'x' = exclusion constraint.
            contype -> Char,
            /// `true` if the constraint is deferrable.
            condeferrable -> Bool,
            /// `true` if the constraint is deferred by default.
            condeferred -> Bool,
            /// `true` if the constraint has been validated.
            convalidated -> Bool,
            /// OID of the table this constraint belongs to, or 0 if not a table constraint.
            conrelid -> Oid,
            /// OID of the domain this constraint belongs to, or 0 if not a domain constraint.
            contypid -> Oid,
            /// OID of the index supporting this constraint (for unique, primary key, or exclusion constraints), or 0 if none.
            conindid -> Oid,
            /// OID of the parent constraint if this is a child in an inheritance hierarchy, else 0.
            conparentid -> Oid,
            /// OID of the referenced table for foreign key constraints, else 0.
            confrelid -> Oid,
            /// Action on update for foreign key:
            /// 'a' = no action, 'r' = restrict, 'c' = cascade, 'n' = set null, 'd' = set default.
            confupdtype -> Char,
            /// Action on delete for foreign key:
            /// 'a' = no action, 'r' = restrict, 'c' = cascade, 'n' = set null, 'd' = set default.
            confdeltype -> Char,
            /// Match type for foreign key:
            /// 'f' = full, 'p' = partial, 's' = simple.
            confmatchtype -> Char,
            /// `true` if the constraint is defined locally (not inherited).
            conislocal -> Bool,
            /// `true` if the constraint cannot be inherited.
            connoinherit -> Bool,
            /// Column numbers of the constrained columns in the table, or `NULL` if not applicable.
            conkey -> Nullable<Array<SmallInt>>,
            /// Column numbers of the referenced columns in the foreign key's referenced table, or `NULL`.
            confkey -> Nullable<Array<SmallInt>>,
            /// Equality operators for the pairs of constrained columns (foreign key), or `NULL`.
            conpfeqop -> Nullable<Array<Oid>>,
            /// Equality operators for pairs of parent and child columns in table inheritance, or `NULL`.
            conppeqop -> Nullable<Array<Oid>>,
            /// Equality operators for referenced columns in the foreign key's referenced table, or `NULL`.
            conffeqop -> Nullable<Array<Oid>>,
            /// Operator OIDs for exclusion constraints; `NULL` if not applicable.
            conexclop -> Nullable<Array<Oid>>,
            /// Check constraint expression as a human-readable string, or `NULL` if not a check constraint.
            conbin -> Nullable<Text>,
        }
    }

    diesel::table! {
        /// `pg_catalog.pg_database` — system catalog containing one row per database.
        /// Stores metadata about databases including encoding, locale, connection limits,
        /// and access control lists.
        pg_catalog.pg_database (oid) {
            /// OID of the database.
            oid -> Oid,
            /// Name of the database.
            datname -> Text,
            /// OID of the role that owns the database.
            datdba -> Oid,
            /// Character encoding for this database (encoding ID from `pg_encoding`).
            encoding -> Integer,
            /// `true` if this is a template database (can be cloned with CREATE DATABASE).
            datistemplate -> Bool,
            /// `true` if connections to this database are allowed.
            datallowconn -> Bool,
            /// Maximum number of concurrent connections (-1 = no limit).
            datconnlimit -> Integer,
            /// All transaction IDs before this one have been replaced with a permanent ID.
            datfrozenxid -> Oid,
            /// All multixact IDs before this one have been replaced with a permanent ID.
            datminmxid -> Oid,
            /// Default tablespace for this database.
            dattablespace -> Oid,
            /// `LC_COLLATE` setting for this database.
            datcollate -> Text,
            /// `LC_CTYPE` setting for this database.
            datctype -> Text,
        }
    }

    diesel::table! {
        /// `pg_index` — system catalog containing one row per index in the database.
        /// Provides low-level metadata about index properties, columns, uniqueness,
        /// and internal system behavior.
        pg_catalog.pg_index (indexrelid) {
            /// OID of the index itself.
            indexrelid -> Oid,
            /// OID of the table the index is defined on.
            indrelid -> Oid,
            /// Total number of columns in the index.
            indnatts -> SmallInt,
            /// Number of key columns used for uniqueness checks (excluding included columns in some versions).
            indnkeyatts -> SmallInt,
            /// `true` if the index enforces uniqueness.
            indisunique -> Bool,
            /// `true` if the index is a primary key.
            indisprimary -> Bool,
            /// `true` if the index is an exclusion constraint index.
            indisexclusion -> Bool,
            /// `true` if the index is immediate (not deferred).
            indimmediate -> Bool,
            /// `true` if the index is clustered on the table.
            indisclustered -> Bool,
            /// `true` if the index is valid (can be used by queries).
            indisvalid -> Bool,
            /// `true` if the index is protected against transaction wraparound issues.
            indcheckxmin -> Bool,
            /// `true` if the index is ready for inserts/updates.
            indisready -> Bool,
            /// `true` if the index is live and actively maintained by the system.
            indislive -> Bool,
            /// `true` if the index is the replication identity of the table.
            indisreplident -> Bool,
            /// Array of attribute numbers of table columns included in the index.
            indkey -> Array<SmallInt>,
            /// Array of OIDs for column collations for the index columns.
            indcollation -> Array<Oid>,
            /// Array of operator class OIDs for the index columns.
            indclass -> Array<Oid>,
            /// Array of index options (per-column flags such as DESC, NULLS FIRST, etc.).
            indoption -> Array<SmallInt>,
            /// Expression tree for the index (if it's an expression index), stored as a node tree string.
            indexprs -> Nullable<Text>,
            /// Partial index predicate (if it's a partial index), stored as a node tree string.
            indpred -> Nullable<Text>,
        }
    }

    diesel::table! {
        /// `pg_catalog.pg_auth_members` — catalog of authorization identifier membership relationships.
        /// Contains information about which roles are members of which other roles.
        pg_catalog.pg_auth_members (roleid, member) {
            /// OID of the role that has members.
            roleid -> diesel::sql_types::Oid,
            /// OID of the role that is a member.
            member -> diesel::sql_types::Oid,
            /// OID of the role that granted this membership.
            grantor -> diesel::sql_types::Oid,
            /// Whether the member can grant this role to others.
            admin_option -> Bool,
        }
    }

    use crate::schema::{
        information_schema::columns::columns,
        pg_catalog::{
            pg_attrdef::pg_attrdef, pg_authid::pg_authid, pg_depend::pg_depend,
            pg_description::pg_description, pg_namespace::pg_namespace, pg_rewrite::pg_rewrite,
            pg_sequence::pg_sequence, pg_type::pg_type,
        },
    };
    diesel::allow_tables_to_appear_in_same_query!(
        pg_attribute,
        pg_class,
        pg_collation,
        pg_constraint,
        pg_index
    );
    diesel::allow_tables_to_appear_in_same_query!(pg_class, columns);
    diesel::allow_tables_to_appear_in_same_query!(pg_class, pg_attrdef);
    diesel::allow_tables_to_appear_in_same_query!(pg_class, pg_depend);
    diesel::allow_tables_to_appear_in_same_query!(pg_class, pg_description);
    diesel::allow_tables_to_appear_in_same_query!(pg_class, pg_namespace);
    diesel::allow_tables_to_appear_in_same_query!(pg_class, pg_rewrite);
    diesel::allow_tables_to_appear_in_same_query!(pg_class, pg_sequence);
    diesel::allow_tables_to_appear_in_same_query!(pg_attribute, columns);
    diesel::allow_tables_to_appear_in_same_query!(pg_attribute, pg_attrdef);
    diesel::allow_tables_to_appear_in_same_query!(pg_attribute, pg_depend);
    diesel::allow_tables_to_appear_in_same_query!(pg_attribute, pg_namespace);
    diesel::allow_tables_to_appear_in_same_query!(pg_attribute, pg_sequence);
    diesel::allow_tables_to_appear_in_same_query!(pg_attribute, pg_type);
    diesel::allow_tables_to_appear_in_same_query!(pg_collation, pg_namespace);
    diesel::allow_tables_to_appear_in_same_query!(pg_class, pg_type);
    diesel::allow_tables_to_appear_in_same_query!(pg_collation, pg_type);
    diesel::allow_tables_to_appear_in_same_query!(pg_auth_members, pg_authid);
}
