-- `serial` and identity columns, whose sequences the engine names
-- `<table>_<column>_seq` and which read origin `Serial` and `Identity`,
-- the owned column answering the default that draws from the sequence.
DROP SCHEMA IF EXISTS app CASCADE;
CREATE SCHEMA app;
CREATE TABLE app.orders (
    order_id BIGINT GENERATED ALWAYS AS IDENTITY,
    default_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    line_no serial,
    big_id BIGSERIAL,
    small_id SMALLSERIAL
);
